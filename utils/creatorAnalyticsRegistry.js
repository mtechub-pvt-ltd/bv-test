export function getModuleByKey(key) {
  return CREATOR_ANALYTICS_MODULES.find((m) => m.key === key) || null;
}

export function getModulesForQuery(moduleKey) {
  if (!moduleKey || moduleKey === "all") return CREATOR_ANALYTICS_MODULES;
  const mod = getModuleByKey(moduleKey);
  return mod ? [mod] : [];
}
